-- Jisr schema for Postgres (Supabase). Applied once; the app does not create tables itself in Postgres mode.
-- Tables live in their own schema, not "public", so they are not exposed through Supabase's Data API.
CREATE SCHEMA IF NOT EXISTS jisr;

CREATE TABLE IF NOT EXISTS jisr.admin (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    username TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS jisr.settings (
    key TEXT PRIMARY KEY,
    value TEXT
);

CREATE TABLE IF NOT EXISTS jisr.payment_methods (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    color TEXT NOT NULL DEFAULT '#00704a',
    logo BYTEA,
    logo_version TEXT,
    sort_order INTEGER NOT NULL DEFAULT 0,
    is_active INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS jisr.transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tx_date TEXT NOT NULL,
    usd_rate DOUBLE PRECISION NOT NULL,
    usd_amount DOUBLE PRECISION NOT NULL,
    cost_mru DOUBLE PRECISION NOT NULL,
    mru_paid DOUBLE PRECISION NOT NULL,
    profit DOUBLE PRECISION NOT NULL,
    method_id BIGINT,
    method_name TEXT NOT NULL DEFAULT '',
    customer TEXT NOT NULL DEFAULT '',
    note TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_tx_date ON jisr.transactions (tx_date DESC);

INSERT INTO jisr.payment_methods (name, color, sort_order)
