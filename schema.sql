-- v9: user accounts with roles (admin / worker). The existing single account becomes the admin.
CREATE TABLE IF NOT EXISTS jisr.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    username TEXT NOT NULL UNIQUE,
    secret_hash TEXT NOT NULL,
    auth_type TEXT NOT NULL DEFAULT 'pin',
    role TEXT NOT NULL DEFAULT 'worker',
    is_active INTEGER NOT NULL DEFAULT 1,
    fail_count INTEGER NOT NULL DEFAULT 0,
    locked_until DOUBLE PRECISION,
    created_at TEXT NOT NULL
);
INSERT INTO jisr.users (name, username, secret_hash, auth_type, role, created_at)
SELECT a.username, a.username, a.password_hash,
       CASE WHEN (SELECT value FROM jisr.settings WHERE key = 'auth_type') = 'pin' THEN 'pin' ELSE 'password' END,
       'admin', a.created_at
FROM jisr.admin a
WHERE NOT EXISTS (SELECT 1 FROM jisr.users);
