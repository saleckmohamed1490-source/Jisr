WHERE NOT EXISTS (SELECT 1 FROM jisr.payment_methods);

REVOKE ALL ON SCHEMA jisr FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL TABLES IN SCHEMA jisr FROM anon, authenticated;

